class Smoke(unittest.TestCase):
    def test_programs(self):
        for case in CASES:
            name, source, expected = case[0], case[1], case[2]
            answers = case[3] if len(case) > 3 else ()
            with self.subTest(name):
                self.assertEqual(run(source, answers), expected)

    def test_errors(self):
        for case in ERRORS:
            name, source, line, fragment = case[:4]
            answers = case[4] if len(case) > 4 else ()
            with self.subTest(name):
                with self.assertRaises(speak.SpeakError) as caught:
                    run(source, answers)
                self.assertIn(fragment, str(caught.exception))
                self.assertEqual(caught.exception.line, line)


