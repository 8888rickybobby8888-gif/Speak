"""Writes LIBRARIES.md from the Speak library files in src/speak_libraries.

Reads the files as text (it does not import them), so it works even when numpy,
pandas, matplotlib or micromelon are not installed.  Run: python make_library_docs.py
"""
import ast
import os
import textwrap

FOLDER = os.path.join('src', 'speak_libraries')
ORDER = ['numpy', 'pandas', 'matplotlib', 'micromelon', 'math', 'random', 'time']
TITLES = {
    'numpy': 'numpy: number crunching with arrays',
    'pandas': 'pandas: tables of data',
    'matplotlib': 'matplotlib: charts',
    'micromelon': 'micromelon: Micromelon rovers',
    'math': 'math: maths',
    'random': 'random: random choices',
    'time': 'time: waiting, timing and dates',
}
INSTALL = {'numpy': 'pip install numpy', 'pandas': 'pip install pandas', 'matplotlib': 'pip install matplotlib',
           'micromelon': 'pip install micromelon'}


def signature(function):
    arguments = function.args
    names = [a.arg for a in arguments.args]
    defaults = [None] * (len(names) - len(arguments.defaults)) + list(arguments.defaults)
    parts = [name if default is None else f'{name}={ast.unparse(default)}' for name, default in zip(names, defaults)]
    return ', '.join(parts)


def paragraphs(docstring):
    """Turns a module docstring into markdown: indented blocks become code blocks."""
    out = []
    for block in textwrap.dedent(docstring).strip().split('\n\n'):
        lines = block.split('\n')
        if all(line.startswith('    ') or not line.strip() for line in lines):
            out.append('```\n' + textwrap.dedent(block).strip('\n') + '\n```')
        else:
            out.append(' '.join(line.strip() for line in lines))
    return '\n\n'.join(out)


def describe(name):
    with open(os.path.join(FOLDER, f'speak_{name}.py'), encoding='utf-8') as handle:
        tree = ast.parse(handle.read())
    intro = paragraphs(ast.get_docstring(tree) or '')
    rows = []
    section = 'Functions'
    sections = []
    # Group by the "# ---- title" comments in the source.
    source = open(os.path.join(FOLDER, f'speak_{name}.py'), encoding='utf-8').read().split('\n')
    headings = {i + 1: line[6:].strip() for i, line in enumerate(source) if line.startswith('# ----')}
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and not node.name.startswith('_'):
            before = [line for line in headings if line < node.lineno]
            title = headings[max(before)] if before else 'Functions'
            summary = (ast.get_docstring(node) or '').split('\n')[0]
            if not sections or sections[-1][0] != title:
                sections.append((title, []))
            sections[-1][1].append((f'{node.name}({signature(node)})', summary))
    return intro, sections


def main():
    lines = [
        '# Speak libraries',
        '',
        'Well-known Python libraries, re-described in plain English with no abbreviations.',
        '',
        '```',
        'use numpy',
        'use micromelon as robot',
        '',
        'scores = numpy.array([4, 8, 15, 16, 23, 42])',
        'print numpy.standard_deviation(scores)',
        '```',
        '',
        '- `use NAME` loads the **Speak version** of a library if there is one (listed below). '
        'For any other installed Python library it gives you the ordinary library, so `use scipy` works too.',
        '- `use NAME as OTHER` picks the name you will type, for example `use micromelon as robot`.',
        '- `use a, b, c` loads several at once.',
        '- Every Speak library has `.raw`, the original Python library, for anything not covered: '
        '`numpy.raw.linalg.norm(values)`.',
        '- `NAME.list_functions()` prints everything a library offers, with descriptions.',
        '- The ordinary Python way (`import numpy as np`) still works and can be mixed with `use`.',
        '- Libraries that are not part of Python must be installed first (for example `pip install numpy`).',
        '- Positions that these libraries return or accept count from **1**, matching `item N of`.',
        '',
        'Contents: ' + ', '.join(f'[{n}](#{n})' for n in ORDER) + '.',
        '',
        '*This file is generated by `make_library_docs.py` from the library files. Edit those, not this.*',
        '',
    ]
    for name in ORDER:
        intro, sections = describe(name)
        lines += ['---', '', f'## {name}', '', f'**{TITLES[name]}**', '']
        if name in INSTALL:
            lines += [f'Install: `{INSTALL[name]}`', '']
        lines += [intro, '']
        for title, rows in sections:
            lines += [f'### {title[0].upper() + title[1:]}' if len(sections) > 1 else '### Functions', '',
                      '| Write | Does |', '| --- | --- |']
            lines += [f'| `{name}.{call}` | {summary} |' for call, summary in rows]
            lines.append('')
    with open('LIBRARIES.md', 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines))
    print('wrote LIBRARIES.md')


if __name__ == '__main__':
    main()
